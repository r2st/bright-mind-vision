// Enhanced search and filtering functions
export function searchProducts(query, filters = {}) {
  const searchTerms = query.toLowerCase().split(/\s+/);
  
  return enhancedLuxuryProducts.filter(product => {
    // Text search across multiple fields
    const searchableText = [
      product.name,
      product.description,
      product.category,
      product.subcategory,
      product.brand,
      product.collection,
      ...product.tags,
      ...product.benefits,
      ...product.keywords
    ].join(' ').toLowerCase();
    
    const textMatch = searchTerms.every(term => 
      searchableText.includes(term)
    );
    
    // Filter by category
    const categoryMatch = !filters.category || 
      product.category.toLowerCase() === filters.category.toLowerCase();
    
    // Filter by price range
    const priceMatch = (!filters.minPrice || product.price >= filters.minPrice) &&
                      (!filters.maxPrice || product.price <= filters.maxPrice);
    
    // Filter by brand
    const brandMatch = !filters.brand || 
      product.brand.toLowerCase() === filters.brand.toLowerCase();
    
    // Filter by availability
    const availabilityMatch = !filters.inStock || product.stock > 0;
    
    return textMatch && categoryMatch && priceMatch && brandMatch && availabilityMatch;
  });
}

export function getProductById(id) {
  return enhancedLuxuryProducts.find(product => product.id === id);
}

export function getProductsByCategory(category) {
  return enhancedLuxuryProducts.filter(product => 
    product.category.toLowerCase() === category.toLowerCase()
  );
}

export function getProductsByBrand(brand) {
  return enhancedLuxuryProducts.filter(product => 
    product.brand.toLowerCase() === brand.toLowerCase()
  );
}

export function getFeaturedProducts(limit = 5) {
  return enhancedLuxuryProducts
    .filter(product => product.rating >= 4.5)
    .sort((a, b) => b.rating - a.rating)
    .slice(0, limit);
}

export function getInvestmentProducts() {
  return enhancedLuxuryProducts
    .filter(product => product.investmentValue === 'High' || product.investmentValue === 'Very High')
    .sort((a, b) => b.price - a.price);
}

export function getExclusiveProducts() {
  return enhancedLuxuryProducts
    .filter(product => product.exclusivity === 'High' || product.exclusivity === 'Highest')
    .sort((a, b) => b.price - a.price);
}
